// Color palette
const COLORS: { [key: string]: string } = {
  "0": "transparent",
  "1": "#e8b896", // Skin tone (muscular highlight)
  "2": "#ffffff", // White (briefs, boots, wristbands)
  "3": "#1a1a1a", // Black (eyes)
  "4": "#ff6b6b", // Red (forehead mark)
  "5": "#d4967a", // Nose/lip shadow
  "6": "#c45c5c", // Mouth
};

interface AvatarProps {
  size?: number;
  pixels?: string[];
  className?: string;
}

export const Avatar: React.FC<AvatarProps> = ({
  size = 128,
  pixels = DEFAULT_AVATAR_PIXELS,
  className = "",
}) => {
  const canvasRef = useRef<HTMLCanvasElement>(null);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;

    const ctx = canvas.getContext("2d");
    if (!ctx) return;

    // Clear canvas
    ctx.clearRect(0, 0, size, size);

    // Calculate pixel size
    const pixelSize = size / 64;

    // Disable image smoothing for crisp pixels
    ctx.imageSmoothingEnabled = false;

    // Draw each pixel
    pixels.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        const colorIndex = row[x];
        const color = COLORS[colorIndex];

        if (color && color !== "transparent") {
          ctx.fillStyle = color;
          ctx.fillRect(
            Math.floor(x * pixelSize),
            Math.floor(y * pixelSize),
            Math.ceil(pixelSize),
            Math.ceil(pixelSize)
          );
        }
      }
    });
  }, [size, pixels]);

  return (
    <canvas
      ref={canvasRef}
      width={size}
      height={size}
      className={`pixelated ${className}`}
      style={{
        imageRendering: "pixelated",
      }}
    />
  );
};

export default Avatar;
